"""GP-preserving shared PS wiring, derived from existing validated front end."""
from pathlib import Path
import re
from prepare_ip import ROOT
def render():
 dma=(ROOT/'rtl/dma_loopback_top.v').read_text();head=dma.split('module dma_loopback_top(',1)[1].split(');')[0]
 hp=[x.strip().rstrip(',') for x in head.splitlines() if 'hp_' in x or 'hp0_aclk' in x]
 # hp0_aclk shares its declaration line with control_rst_n, already exposed.
 hp=[x for x in hp if 'hp0_aclk' not in x]+['output wire hp0_aclk']
 names=[]
 for line in hp:names.append(line.split()[-1])
 shared_ports=head.replace('output wire hp0_aclk,control_rst_n','output wire hp0_aclk,control_rst_n')
 shared_ports=shared_ports.replace('input wire clk_100m,arst_n','input wire clk_100m,arst_n,rst_n')
 text='// Generated by generate_shared.py; GP ABI and source module unchanged.\n`include "generated/interface_defs.vh"\nmodule dma_shared_lite_top('+shared_ports+');\n'
 types={'awaddr':33,'araddr':33,'wdata':32,'wstrb':4,'bresp':2,'rdata':32,'rresp':2}
 sig=['awaddr','araddr','wdata','wstrb','awvalid','awready','wvalid','wready','bvalid','bready','bresp','arvalid','arready','rvalid','rready','rdata','rresp']
 for n in sig:
  w=types.get(n,1)*2;text+=f'wire [{w-1}:0] m_{n};\n'
 text+='axi_lite_two_way router(.clk(clk_100m),.rst_n(rst_n),'+','.join(f'.s_{n}(s_{n})' for n in sig)+','+','.join(f'.m_{n}(m_{n})' for n in sig)+');\nwire gp_irq;wire [15:0] dma_irq;\n'
 def binds(index):
  return ','.join(f'.s_{n}(m_{n}[{index*types.get(n,1)}+: {types.get(n,1)}])' for n in sig)
 text+='gp_control_regs registers(.clk(clk_100m),.rst_n(rst_n),'+binds(0)+',.actual_position(256\'d0),.actual_pulses(256\'d0),.actual_valid(4\'d0),.actual_state(`PLI_STATE_NOT_READY),.actual_session(64\'d0),.actual_accepted_seq(32\'hffffffff),.actual_done_seq(32\'hffffffff),.irq(gp_irq));\n'
 text+='dma_loopback_top dma_core(.clk_100m(clk_100m),.arst_n(arst_n),.control_rst_n(control_rst_n),.f2p_irq(dma_irq),.loop_occupancy(loop_occupancy),'+binds(1)+','+','.join(f'.{n}({n})' for n in names)+');\n'
 text+='assign f2p_irq=dma_irq | (gp_irq ? 16\'d1 : 16\'d0);\nendmodule\n'
 front=(ROOT.parent/'pl_motion/rtl/gp_control_top.v').read_text()
 front=front.replace('module gp_control_top(','module dma_gp_full_top(').replace('// No physical motor outputs or DMA. Use the installed vendor converter RTL.','// Shared GP/DMA control front end; original GP implementation is unchanged.')
 split=front.index(');');front=front[:split]+',\n'+',\n'.join(hp)+front[split:]
 start=front.index('    gp_control_regs registers(');front=front[:start]
 # Original IRQ expression has no driver in the derived front end.
 start=front.index('    wire irq;');end=front.index('    wire [32:0] s_awaddr',start);front=front[:start]+front[end:]
 front+='dma_shared_lite_top fabric(.clk_100m(clk_100m),.arst_n(arst_n),.rst_n(control_rst_n),.control_rst_n(),.f2p_irq(f2p_irq),.loop_occupancy(),'+','.join(f'.s_{n}(s_{n})' for n in sig)+','+','.join(f'.{n}({n})' for n in names)+');\nendmodule\n'
 ps=(ROOT.parent/'pl_motion/rtl/gp_ps_control_top.v').read_text().replace('module gp_ps_control_top(','module dma_gp_ps_top(').replace('gp_control_top core(','dma_gp_full_top core(')
 split=ps.index(');');ps=ps[:split]+',\n'+',\n'.join(hp)+ps[split:]
 pos=ps.rindex('\n);');ps=ps[:pos]+',\n'+',\n'.join(f'.{n}({n})' for n in names)+ps[pos:]
 return {'dma_shared_lite_top.v':text,'dma_gp_full_top.v':front,'dma_gp_ps_top.v':ps}
if __name__=='__main__':
 import argparse
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for name,text in render().items():
  p=ROOT/'rtl'/name
  if a.check:
   if p.read_text()!=text:raise SystemExit('stale '+name)
  else:p.write_text(text,encoding='utf-8')
