"""Controlled gate-only matrix, common scan fixture and peripheral wrapper."""
import argparse,json,re,shutil
from experiment import E,R,TD,IP,run_td
G=E/'build/al_ip'
Q=json.loads((R/'pl_rs485/evidence/identity_telemetry.json').read_text())['effective_s2mm_parameters']
BASE=(R/'pl_dma/rtl/telemetry_dma_lite_top.v').read_text()
for k in sorted(Q,key=len,reverse=True): BASE=BASE.replace('`PLI_TELEM_DMA_'+k,str(Q[k]))

def official(index):return G/f'AXI_DMA_{index}'/f'AXI_DMA_{index}.v'

def make(tag,kind):
    b=E/'build'/tag;b.mkdir(parents=True,exist_ok=False)
    text=BASE;libs=[IP/'axi_dma.v'];extra=[]
    if kind.startswith('official'):
        idx=int(kind[-1]);src=official(idx);raw=src.read_text()
        ports=re.findall(r'^\s*(?:input|output)\s+(?:\[[^]]+\]\s*)?(\w+)\s*[,\n]',raw,re.M)
        assert len(ports)==46,len(ports)
        binds=',\n'.join(f'.{p}(d_{p})' for p in ports)
        text=re.sub(r'axi_dma #\(.*?\) dma \(.*?\);',f'AXI_DMA_{idx} dma ({binds});',text,flags=re.S)
        # Removed read bus is terminated outside generated IP, same peripheral.
        text+='\n' if text.endswith('\n') else ''
        ties='\n'.join('assign d_'+p+'=0;' for p in ['m_axi_mm2s_araddr','m_axi_mm2s_arlen','m_axi_mm2s_arsize','m_axi_mm2s_arburst','m_axi_mm2s_arprot','m_axi_mm2s_arcache','m_axi_mm2s_arvalid','m_axi_mm2s_rready'])
        text=text.replace('endmodule',ties+'\nendmodule')
        libs=[G/f'AXI_DMA_{idx}'/'RTL'/f'axi_dma_AXI_DMA_{idx}.v',src]
    elif kind=='params_official':
        raw=official(1).read_text();ps=re.search(r'#\((.*?)\)axi_dma_Inst',raw,re.S)[1]
        text=re.sub(r'axi_dma #\(.*?\) dma',lambda m:'axi_dma #(\n'+ps+') dma',text,flags=re.S)
    elif kind=='ports_official':
        raw=official(1).read_text();ports=re.findall(r'^\s*(?:input|output)\s+(?:\[[^]]+\]\s*)?(\w+)\s*[,\n]',raw,re.M)
        text=re.sub(r'\) dma \(.*?\);',') dma ('+',\n'.join(f'.{p}(d_{p})' for p in ports)+');',text,flags=re.S)
        ties='\n'.join('assign d_'+p+'=0;' for p in ['m_axi_mm2s_araddr','m_axi_mm2s_arlen','m_axi_mm2s_arsize','m_axi_mm2s_arburst','m_axi_mm2s_arprot','m_axi_mm2s_arcache','m_axi_mm2s_arvalid','m_axi_mm2s_rready'])
        text=text.replace('endmodule',ties+'\nendmodule')
    elif kind!='baseline':
        key,value=kind.split('=');text,n=re.subn(r'(\.'+key+r'\()\d+(\))',lambda m:m[1]+value+m[2],text);assert n==1
    text=text.replace('// Generated by pl_dma/generate_top.py; edit schema or generator.','// Experimental derivative; production source unchanged.')
    (b/'telemetry_dma_lite_top.v').write_text(text)
    shutil.copyfile(R/'pl_dma/rtl/telemetry_dma_guard.v',b/'telemetry_dma_guard.v')
    shutil.copyfile(R/'pl_dma/reports/telem_dma_r1/top.v',b/'top.v')
    (b/'generated').mkdir();shutil.copyfile(R/'pl_interface/generated/interface_defs.vh',b/'generated/interface_defs.vh')
    for name in ['axi_dma_func_pkg.vh','axi_dma_param_pkg.vh']:shutil.copyfile(IP/name,b/name)
    converter=TD/'ip/depot/AXI_Protocol_Converter_1.0/AXI_MM/RTL/axi_protocol_converter_merge.v'
    files=libs+[converter,b/'telemetry_dma_guard.v',b/'telemetry_dma_lite_top.v',b/'top.v']
    (b/'sources.json').write_text(json.dumps([p.as_posix() for p in files],indent=2))
    (b/'clock.sdc').write_text('create_clock -name telem_clk -period 10 [get_ports clk]\n')
    script=f'cd {{{b.as_posix()}}}\nimport_device dr1_90.db -package DR1M90GEG400 -speed 2\nset_param flow thread 16\nget_num_thread\n'
    script+=''.join(f'analyze -file {{{p.as_posix()}}}\n' for p in files)
    script+='elaborate -top telem_probe\noptimize_rtl\nread_sdc clock.sdc\noptimize_gate -maparea gate.area\nexport_db gate.db\nwrite_verilog gate.v\nget_num_thread\nputs EXPERIMENT_COMPLETE\nexit\n'
    rc=run_td(b,script);log=(b/'run.log').read_text()
    result={'tag':tag,'kind':kind,'exit':rc,'complete':'EXPERIMENT_COMPLETE' in log,'threads':re.findall(r'Number of Thread = (\d+)',log),'diagnostics':[x for x in log.splitlines() if re.search(r' (?:CRITICAL-WARNING|WARNING|ERROR):',x)]}
    if (b/'gate.area').exists():
        area=(b/'gate.area').read_text();result['resources']={k:int(re.search(re.escape(k)+r'\s+(\d+)',area)[1]) for k in ['#unit lut*','#slice reg','#eram','#dsp','#lut']}
    (b/'result.json').write_text(json.dumps(result,indent=2));print(json.dumps({k:v for k,v in result.items() if k!='diagnostics'}))
    assert result['complete'] and not re.search(r' ERROR:',log)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('tag');ap.add_argument('kind');a=ap.parse_args();make(a.tag,a.kind)
