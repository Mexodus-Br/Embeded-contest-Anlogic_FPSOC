"""Generate only wiring from audited vendor ports and the unique schema."""
import argparse
from pathlib import Path
from prepare_ip import ROOT,profile,dma_ports
def render():
    p=profile();ports=dma_ports();lines=['// Generated by pl_dma/generate_top.py; edit schema or generator.',
      '`timescale 1ns/1ps','`include "generated/interface_defs.vh"']
    hp={}
    for n,(d,w) in ports.items():
        if n.startswith('m_axi_mm2s_') or n.startswith('m_axi_s2mm_'):
            tail=n.split('_',3)[3]
            if tail=='aclk' or tail.endswith('user'):continue
            hp[tail]=(d,33 if tail in ['awaddr','araddr'] else 4 if tail in ['awlen','arlen'] else 2 if tail in ['awsize','arsize'] else w)
    hp.update({'awid':('output',6),'arid':('output',6),'bid':('input',6),'rid':('input',6),'awlock':('output',1),'arlock':('output',1),'awqos':('output',4),'arqos':('output',4)})
    declarations=['input wire clk_100m,arst_n','output wire hp0_aclk,control_rst_n','output wire [15:0] f2p_irq',
      'input wire [32:0] s_awaddr,s_araddr','input wire s_awvalid,s_wvalid,s_bready,s_arvalid,s_rready',
      'output wire s_awready,s_wready,s_bvalid,s_arready,s_rvalid','input wire [31:0] s_wdata',
      'input wire [3:0] s_wstrb','output wire [31:0] s_rdata','output wire [1:0] s_bresp,s_rresp',
      'output wire [31:0] loop_occupancy']
    for n,(d,w) in hp.items():declarations.append(d+' wire '+(f'[{w-1}:0] ' if w>1 else '')+'hp_'+n)
    lines+=['module dma_loopback_top(\n '+',\n '.join(declarations)+'\n);',
      'reg [1:0] reset_release; always @(posedge clk_100m or negedge arst_n) if(!arst_n) reset_release<=0; else reset_release<={reset_release[0],1\'b1};',
      'assign control_rst_n=reset_release[1]; assign hp0_aclk=clk_100m;']
    for n,(d,w) in ports.items():lines.append('wire '+(f'[{w-1}:0] ' if w>1 else '')+'d_'+n+';')
    lines+=['dma_lite_guard guard(.clk(clk_100m),.rst_n(control_rst_n),']
    bind=[]
    for n in ['awaddr','awvalid','awready','wdata','wstrb','wvalid','wready','bresp','bvalid','bready','araddr','arvalid','arready','rdata','rresp','rvalid','rready']:bind.append(f'.s_{n}(s_{n})')
    for n in ['awaddr','awvalid','awready','wdata','wvalid','wready','bresp','bvalid','bready','araddr','arvalid','arready','rdata','rresp','rvalid','rready']:bind.append(f'.m_{n}(d_s_axi_lite_{n})')
    lines+=[',\n'.join(bind)+');']
    for n,(d,w) in ports.items():
        if d!='input':continue
        value=None
        if n.endswith('_aclk'):value='clk_100m'
        elif n=='axi_resetn':value='control_rst_n'
        elif n.startswith('m_axi_sg_'):value=f"{w}'d0"
        elif n.startswith('m_axis_mm2s_cntrl_'):value="1'b1"
        elif n.startswith('s_axis_s2mm_sts_'):value=f"{w}'d0"
        if value is not None:lines.append(f'assign d_{n}={value};')
    lines+=['axi_dma #(\n '+',\n '.join(f'.{n}(`PLI_DMA_DMA_LOOPBACK_V1_{n})' for n in p['parameters'])+'\n) dma (',',\n'.join(f'.{n}(d_{n})' for n in ports)+');']
    lines+=['wire fifo_arst_n=control_rst_n && d_mm2s_prmry_reset_out_n && d_s2mm_prmry_reset_out_n;',
      'reg [1:0] fifo_release; always @(posedge clk_100m or negedge fifo_arst_n) if(!fifo_arst_n) fifo_release<=0; else fifo_release<={fifo_release[0],1\'b1};',
      'axis_loop_fifo #(.DEPTH(`PLI_DMA_DMA_LOOPBACK_V1_FIFO_DEPTH)) loop_fifo(.clk(clk_100m),.rst_n(fifo_release[1]),']
    fb=[]
    for pre,dpre in [('s','m_axis_mm2s'),('m','s_axis_s2mm')]:
        for n in ['data','keep','last','valid','ready','user','id','dest']:fb.append(f'.{pre}_{n}(d_{dpre}_t{n})')
    lines+=[',\n'.join(fb)+',.occupancy(loop_occupancy));',
      'assign f2p_irq=(!arst_n || !control_rst_n) ? 16\'d0 : ((d_mm2s_introut ? (16\'d1<<`PLI_DMA_DMA_LOOPBACK_V1_IRQ_MM2S_LINE) : 16\'d0) | (d_s2mm_introut ? (16\'d1<<`PLI_DMA_DMA_LOOPBACK_V1_IRQ_S2MM_LINE) : 16\'d0));']
    # Merge disjoint MM2S read and S2MM write channels; real converter retains
    # AXI3 burst/response ownership. No invented address or ID truncation.
    lines+=['wire [2:0] bridge_awsize,bridge_arsize;wire [1:0] bridge_awlock,bridge_arlock;',
      'assign hp_awsize=bridge_awsize[1:0]; assign hp_arsize=bridge_arsize[1:0];',
      'assign hp_awlock=bridge_awlock[0]; assign hp_arlock=bridge_arlock[0];',
      'axi_protocol_converter_merge #(.AL_US_AXI_PROTOCOL(0),.AL_DS_AXI_PROTOCOL(1),.AL_AXI_ID_WIDTH(6),.AL_AXI_ADDR_WIDTH(33),.AL_AXI_DATA_WIDTH(64),.AL_AXI_SUPPORTS_USER_SIGNALS(0)) hp_converter(.aclk(clk_100m),.aresetn(control_rst_n),']
    cb=[]
    for ch,dp in [('aw','m_axi_s2mm'),('w','m_axi_s2mm'),('b','m_axi_s2mm'),('ar','m_axi_mm2s'),('r','m_axi_mm2s')]:
        for n,(d,w) in ports.items():
            if n.startswith(dp+'_'+ch):
                tail=n[len(dp)+1:]
                if tail.endswith('user'):continue
                val='d_'+n
                if tail in ['awaddr','araddr']:val="{1'b0,"+val+'}'
                cb.append(f'.us_axi_{tail}({val})')
    for n in ['awid','arid','wid']:cb.append(f'.us_axi_{n}(6\'d0)')
    for n in ['awlock','arlock','awuser','aruser','wuser']:cb.append(f'.us_axi_{n}(1\'b0)')
    for n in ['awqos','arqos','awregion','arregion']:cb.append(f'.us_axi_{n}(4\'d0)')
    for n in ['bid','rid','buser','ruser']:cb.append(f'.us_axi_{n}()')
    for n in hp:
        val='bridge_'+n if n in ['awsize','arsize','awlock','arlock'] else 'hp_'+n
        cb.append(f'.ds_axi_{n}({val})')
    for n in ['buser','ruser']:cb.append(f'.ds_axi_{n}(1\'b0)')
    for n in ['awuser','aruser','wuser','wid','awregion','arregion']:cb.append(f'.ds_axi_{n}()')
    lines+=[',\n'.join(cb)+');','endmodule','']
    return '\n'.join(lines)
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    target=ROOT/'rtl/dma_loopback_top.v';t=render()
    if a.check:
        if target.read_text()!=t:raise SystemExit('stale DMA wiring')
    else:target.write_text(t,encoding='utf-8')
