"""New candidate wrappers; legacy generated top-level files remain untouched."""
import argparse,re
from pathlib import Path
R=Path(__file__).resolve().parents[1];D=R/'pl_safety'
SIG=['awaddr','araddr','wdata','wstrb','awvalid','awready','wvalid','wready','bvalid','bready','bresp','arvalid','arready','rvalid','rready','rdata','rresp']
WIDTH={'awaddr':33,'araddr':33,'wdata':32,'wstrb':4,'bresp':2,'rdata':32,'rresp':2}
def expand_bus(s):
 s=re.sub(r'\[(197|191|23):0\]',lambda m:'['+{'197':'230','191':'223','23':'27'}[m[1]]+':0]',s)
 for a,b in [('11:0] m_bresp','13:0] m_bresp'),('11:0] m_rresp','13:0] m_rresp'),('5:0] m_','6:0] m_'),('{6{','{7{'),("6'b000001","7'b0000001")]:s=s.replace(a,b)
 return s
def addports(s,extra):
 at=s.index(');',s.index('module '));return s[:at].rstrip()+',\n'+extra+'\n'+s[at:]
def render():
 result={}
 t=expand_bus((R/'pl_dma/rtl/axi_lite_six_way.v').read_text()).replace('axi_lite_six_way','safety_axi_lite_seven_way')
 t='`include "safety_defs.vh"\n'+t
 for n in ['aw','ar']:
  old=f's_{n}addr[32:12]==GP_BASE[32:12] ?'
  t=t.replace(old,f"s_{n}addr[32:12]==(`SAF_BASE>>12) ? 6 : "+old)
 result['safety_axi_lite_seven_way.v']=t
 raw='input wire [2:0] safety_limit_n,input wire safety_estop_n'
 extra=['input wire [63:0] shared_time_us','output wire safety_irq']
 for n in SIG:
  d='input' if n in ['awaddr','araddr','wdata','wstrb','awvalid','wvalid','bready','arvalid','rready'] else 'output'
  w=WIDTH.get(n,1);extra.append(d+' wire '+(f'[{w-1}:0] ' if w>1 else '')+'safety_'+n)
 for name in ['motion_dma_lite_top','rs485_shared_lite_top','rs485_gp_full_top','rs485_gp_ps_top']:
  s=(R/'pl_dma/rtl'/f'{name}.v').read_text()
  s=s.replace('module '+name,'module safety_'+name).replace('parameter [3:0] EN_ACTIVE_LEVEL=15','parameter [3:0] EN_ACTIVE_LEVEL=15,parameter CONFIG_PROFILE=0')
  s=addports(s,raw+(',\n'+',\n'.join(extra) if name=='motion_dma_lite_top' else ''))
  if name=='motion_dma_lite_top':
   s=s.replace('motion_service #(','safety_motion_service #(.CONFIG_PROFILE(CONFIG_PROFILE),')
   s=s.replace('motion(.clk(clk_100m),', 'motion(.limit_n(safety_limit_n),.estop_n(safety_estop_n),.shared_time_us(shared_time_us),.safety_irq(safety_irq),'+','.join(f'.saf_{n}(safety_{n})' for n in SIG)+',.clk(clk_100m),')
  elif name=='rs485_shared_lite_top':
   s=expand_bus(s).replace('axi_lite_six_way router','safety_axi_lite_seven_way router')
   s=s.replace('motion_dma_lite_top #(','safety_motion_dma_lite_top #(.CONFIG_PROFILE(CONFIG_PROFILE),')
   s=s.replace('dma_core(', 'dma_core(.safety_limit_n(safety_limit_n),.safety_estop_n(safety_estop_n),.shared_time_us(system_time_us),.safety_irq(safety_irq),'+','.join(f'.safety_{n}(m_{n}[{6*WIDTH.get(n,1)}+:{WIDTH.get(n,1)}])' for n in SIG)+',')
   s=s.replace('wire gp_irq,motion_irq,rs_irq,telem_irq;','wire gp_irq,motion_irq,rs_irq,telem_irq,safety_irq;')
   s=s.replace('assign f2p_irq=','assign f2p_irq=(safety_irq ? (16\'d1<<7):16\'d0) | ')
  else:
   child='rs485_shared_lite_top' if name=='rs485_gp_full_top' else 'rs485_gp_full_top'
   inst='fabric' if name=='rs485_gp_full_top' else 'core'
   s=s.replace(child+' #(','safety_'+child+' #(.CONFIG_PROFILE(CONFIG_PROFILE),')
   s=s.replace(inst+'(',inst+'(.safety_limit_n(safety_limit_n),.safety_estop_n(safety_estop_n),')
  result['safety_'+name+'.v']='// Generated by pl_safety/generate_top.py. Independent safety candidate.\n'+s
 # SAF2 is a separate opt-in chain at the same seven physical windows. The
 # existing SAF1 generated wrappers remain byte-for-byte reproducible.
 for name in ['motion_dma_lite_top','rs485_shared_lite_top','rs485_gp_full_top','rs485_gp_ps_top']:
  s=result['safety_'+name+'.v']
  for child in ['motion_dma_lite_top','rs485_shared_lite_top','rs485_gp_full_top','rs485_gp_ps_top']:
   s=s.replace('safety_'+child,'interlock_'+child)
  if name=='motion_dma_lite_top':
   ports='''input wire collector_run,collector_stop_commit,collector_reset,collector_config_pending,collector_config_stored_pending,collector_config_change,collector_busy,
input wire [31:0] collector_generation,collector_revision,collector_next_generation,collector_next_revision,
input wire collector_next_reset,collector_next_config_change,
input wire [159:0] collector_periods,input wire [4:0] collector_mask,
input wire feedback_commit,input wire [255:0] feedback_raw,input wire [5:0] feedback_predecoded,
input wire collector_query_ok,input wire [1:0] feedback_time_valid,output wire [63:0] feedback_round_reference,
output wire interlock_idle,interlock_idle_off'''
   s=addports(s,ports)
   s=s.replace('safety_motion_service #(','safety_motion_service #(.INTERLOCK_SUPPORT(1),')
   s=s.replace(' motion(', ' motion(.collector_run(collector_run),.collector_stop_commit(collector_stop_commit),.collector_reset(collector_reset),'+
     '.collector_config_pending(collector_config_pending),.collector_config_stored_pending(collector_config_stored_pending),.collector_config_change(collector_config_change),.collector_busy(collector_busy),'+
     '.collector_next_reset(collector_next_reset),.collector_next_config_change(collector_next_config_change),.collector_generation(collector_generation),.collector_revision(collector_revision),.collector_next_generation(collector_next_generation),.collector_next_revision(collector_next_revision),'+
     '.collector_periods(collector_periods),.collector_mask(collector_mask),'+
     '.feedback_commit(feedback_commit),.feedback_raw(feedback_raw),.feedback_predecoded(feedback_predecoded),.collector_query_ok(collector_query_ok),.feedback_time_valid(feedback_time_valid),.feedback_round_reference(feedback_round_reference),'+
     '.interlock_idle(interlock_idle),.interlock_idle_off(interlock_idle_off),')
  elif name=='rs485_shared_lite_top':
   events='wire completed_valid;wire [255:0] completed_raw;wire [31:0] generation,revision;wire [159:0] periods;wire [4:0] query_mask;'
   assert s.count(events)==1
   s=s.replace(events,'')
   s=s.replace('wire [230:0] m_awaddr;',
     'wire interlock_idle,interlock_idle_off,collector_run,collector_stop_commit,collector_reset,collector_config_pending,collector_config_stored_pending,collector_config_change,collector_busy;\n'+
     events+'\nwire [63:0] completed_round_reference;wire [1:0] completed_time_valid;wire collector_query_ok;\nwire [5:0] completed_protection;\nwire collector_next_reset,collector_next_config_change;\nwire [31:0] collector_next_generation,collector_next_revision;\nwire [230:0] m_awaddr;')
   s=s.replace(' dma_core(', ' dma_core(.collector_run(collector_run),.collector_stop_commit(collector_stop_commit),.collector_reset(collector_reset),'+
     '.collector_config_pending(collector_config_pending),.collector_config_stored_pending(collector_config_stored_pending),.collector_config_change(collector_config_change),.collector_busy(collector_busy),'+
     '.collector_next_reset(collector_next_reset),.collector_next_config_change(collector_next_config_change),.collector_generation(generation),.collector_revision(revision),.collector_next_generation(collector_next_generation),.collector_next_revision(collector_next_revision),'+
     '.collector_periods(periods),.collector_mask(query_mask),'+
     '.feedback_commit(completed_valid),.feedback_raw(completed_raw),.feedback_predecoded(completed_protection),.collector_query_ok(collector_query_ok),.feedback_time_valid(completed_time_valid),.feedback_round_reference(completed_round_reference),'+
     '.interlock_idle(interlock_idle),.interlock_idle_off(interlock_idle_off),')
   s=s.replace('rs485_gp_bridge rs485(', 'rs485_gp_bridge #(.INTERLOCK_SUPPORT(1)) rs485('+
     '.protection_query_ok(collector_query_ok),.completed_protection(completed_protection),.next_round_reference(completed_round_reference),.completed_time_valid(completed_time_valid),.interlock_idle(interlock_idle),.interlock_idle_off(interlock_idle_off),'+
     '.interlock_run(collector_run),.interlock_stop_commit(collector_stop_commit),.interlock_reset(collector_reset),.next_reset(collector_next_reset),.next_config_change(collector_next_config_change),.next_generation(collector_next_generation),.next_revision(collector_next_revision),'+
     '.interlock_config_pending(collector_config_pending),.interlock_config_stored_pending(collector_config_stored_pending),.interlock_config_change(collector_config_change),.interlock_busy(collector_busy),')
  result['interlock_'+name+'.v']=s
 return result
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for n,s in render().items():
  p=D/'generated'/n
  if a.check:assert p.read_bytes()==s.encode(),n
  else:p.write_bytes(s.encode())
 print('PASS safety candidate top generation'+(' check' if a.check else ''))
if __name__=='__main__':main()
