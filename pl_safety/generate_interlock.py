"""Generate SAF2 constants only from the canonical shared schema."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def constants():
    schema = json.loads((ROOT / 'pl_interface/schema.json').read_text(encoding='utf-8'))
    p = schema['interlock_profiles']['gp_safety_interlock_v2']
    old = schema['safety_profiles']['gp_safety_home_v1']
    offsets = list(p['registers'].values())
    assert p['base'] == old['base'] and p['size'] == old['size']
    assert p['profile'] == int.from_bytes(b'SAF2', 'little')
    assert len(offsets) == len(set(offsets)) and all(0x100 <= x < 0x200 and x % 4 == 0 for x in offsets)
    assert p['timeout_min_us'] <= p['timeout_default_us'] <= p['timeout_max_us']
    assert p['heartbeat_period_us'] < p['timeout_min_us']
    result = {k.upper(): v for k, v in p.items() if type(v) is int}
    for group, prefix in [('registers', 'REG_'), ('causes', 'CAUSE_'), ('errors', 'ERR_'), ('snapshot', 'SNAP_')]:
        result.update({prefix + k: v for k, v in p[group].items()})
    result.update({'STATUS_' + k: 1 << v for k, v in p['status_bits'].items()})
    result.update({'FEATURE_' + k: 1 << v for k, v in p['feature_bits'].items()})
    assert p['collector_profile'] == int.from_bytes(b'R5S2', 'little')
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    values = constants()
    v = ['// Generated by generate_interlock.py from pl_interface/schema.json.',
         '`ifndef SAFETY_INTERLOCK_DEFS_VH', '`define SAFETY_INTERLOCK_DEFS_VH']
    h = ['/* Generated from pl_interface/schema.json. */', '#ifndef SAFETY_INTERLOCK_DEFS_H',
         '#define SAFETY_INTERLOCK_DEFS_H', '#include <stdint.h>']
    for name, value in values.items():
        v.append(f"`define SI_{name} 32'h{value:08x}")
        h.append(f'#define SI_{name} UINT32_C(0x{value:08x})')
    for name, lines, end in [('interlock_defs.vh', v, '`endif'), ('interlock_defs.h', h, '#endif')]:
        expected = ('\n'.join(lines + [end, ''])).encode()
        path = ROOT / 'pl_safety/generated' / name
        if args.check:
            assert path.read_bytes() == expected, path
        else:
            path.write_bytes(expected)
    lines = ['// Generated from pl_interface/schema.json by pl_safety/generate_interlock.py.',
             '`ifndef RS485_INTERLOCK_GP_DEFS_VH', '`define RS485_INTERLOCK_GP_DEFS_VH']
    lines += [f"`define RGI_{key[10:]} 32'h{value:08x}" for key,value in values.items()
              if key.startswith('COLLECTOR_')]
    expected = ('\n'.join(lines + ['`endif', ''])).encode()
    path = ROOT / 'pl_rs485/generated/interlock_gp_defs.vh'
    if args.check:
        assert path.read_bytes() == expected, path
    else:
        path.write_bytes(expected)
    profile = json.loads((ROOT / 'pl_interface/schema.json').read_text(encoding='utf-8'))['interlock_profiles']['gp_safety_interlock_v2']
    doc = ['# SAF2 generated register and bit tables', '',
           'Source: pl_interface/schema.json. Access/side effects: ../INTERLOCK_CONTRACT.md.', '',
           '|Register|Offset|', '|---|---:|']
    doc += [f'|{key}|0x{value:03x}|' for key, value in profile['registers'].items()]
    for group in ['status_bits', 'feature_bits', 'causes', 'errors', 'snapshot']:
        doc += ['', '## ' + group, '', '|Name|Value|', '|---|---:|']
        doc += [f'|{key}|{value}|' for key, value in profile[group].items()]
    expected = ('\n'.join(doc) + '\n').encode()
    path = ROOT / 'pl_safety/generated/interlock_registers.md'
    if args.check:
        assert path.read_bytes() == expected, path
    else:
        path.write_bytes(expected)
    print('PASS SAF2 generated definitions' + (' check' if args.check else ''))


if __name__ == '__main__':
    main()
